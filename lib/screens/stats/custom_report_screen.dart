/// Premium report builder – choose a range, sections and export a branded PDF.
class CustomReportScreen extends ConsumerStatefulWidget {
  const CustomReportScreen({super.key});

  @override
  ConsumerState<CustomReportScreen> createState() => _CustomReportScreenState();
}

class _CustomReportScreenState extends ConsumerState<CustomReportScreen> {
  final TextEditingController _titleController =
      TextEditingController(text: 'My money report');
  final TextEditingController _footerController =
      TextEditingController(text: 'Built with MoneyMan');
  late StatsRange _range = defaultStatsRange();
  bool _includeCategories = true;
  bool _includeTransactions = true;
  bool _includeAccounts = true;
  bool _branding = true;
  bool _preparing = false;
  PeriodSummary? _summary;
  List<CategoryTotal> _categories = const <CategoryTotal>[];
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _load();
  }

  @override
  void dispose() {
    _titleController.dispose();
    _footerController.dispose();
    super.dispose();
  }

  Future<void> _load() async {
    setState(() => _loading = true);
    final stats = ref.read(statsRepositoryProvider);
    final summary = await stats.summary(_range.start, _range.end);
    final categories = await stats.categoryTotals(_range.start, _range.end);
    if (!mounted) return;
    setState(() {
      _summary = summary;
      _categories = categories;
      _loading = false;
    });
  }

  Future<void> _export() async {
    setState(() => _preparing = true);
    try {
      final file = await ref.read(exportRepositoryProvider).exportPdf(
            start: _range.start,
            end: _range.end,
            title: _titleController.text.trim().isEmpty
                ? 'Money report'
                : _titleController.text.trim(),
            includeTransactions: _includeTransactions,
            premiumBranding: _branding,
            footer: _footerController.text.trim().isEmpty
                ? 'Generated by MoneyMan'
                : _footerController.text.trim(),
          );
      if (!mounted) return;
      await Share.shareXFiles(<XFile>[XFile(file.path)], text: 'MoneyMan report');
      if (!mounted) return;
      showSnack(context, 'Report ready: ${file.path.split('/').last}');
    } catch (error) {
      if (mounted) showSnack(context, 'Could not build the PDF: $error', error: true);
    } finally {
      if (mounted) setState(() => _preparing = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final palette = context.c;
    final summary = _summary ?? const PeriodSummary();
    final accounts =
        ref.watch(accountsProvider).valueOrNull ?? const <Account>[];

    return Scaffold(
      backgroundColor: palette.surface,
      appBar: AppBar(
        title: Row(
          children: <Widget>[
            const Text('Custom report'),
            const SizedBox(width: 8),
            const PremiumBadge(dense: true),
          ],
        ),
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(
          AppSpacing.screen,
          AppSpacing.x2,
          AppSpacing.screen,
          AppSpacing.x10,
        ),
        children: <Widget>[
          AppTextField(
            controller: _titleController,
            label: 'Report title',
            hint: 'e.g. October spending review',
          ),
          const SizedBox(height: AppSpacing.x4),
          Text('Date range', style: AppTextStyles.label(palette.sub)),
          const SizedBox(height: 8),
          DateRangeChips(
            ranges: buildDateRanges(firstDayOfWeek: 7),
            selectedLabel: _range.label,
            onSelected: (value) {
              setState(() {
                _range = StatsRange(label: value.label, start: value.start, end: value.end);
              });
              _load();
            },
            onCustom: () async {
              final custom = await pickCustomRange(context, start: _range.start);
              if (custom == null) return;
              setState(() {
                _range = StatsRange(label: 'Custom', start: custom.start, end: custom.end);
              });
              _load();
            },
          ),
          const SizedBox(height: AppSpacing.x5),
          Text('Sections', style: context.h3),
          const SizedBox(height: 8),
          AppCard(
            padding: const EdgeInsets.symmetric(horizontal: AppSpacing.x4, vertical: 4),
            child: Column(
              children: <Widget>[
                SwitchRow(
                  title: 'Category breakdown',
                  value: _includeCategories,
                  onChanged: (value) => setState(() => _includeCategories = value),
                  icon: Icons.pie_chart_outline_rounded,
                ),
                Divider(color: palette.divider, height: 1),
                SwitchRow(
                  title: 'Transaction list',
                  value: _includeTransactions,
                  onChanged: (value) => setState(() => _includeTransactions = value),
                  icon: Icons.receipt_long_outlined,
                ),
                Divider(color: palette.divider, height: 1),
                SwitchRow(
                  title: 'Account summary',
                  value: _includeAccounts,
                  onChanged: (value) => setState(() => _includeAccounts = value),
                  icon: Icons.account_balance_wallet_outlined,
                ),
                Divider(color: palette.divider, height: 1),
                SwitchRow(
                  title: 'Premium branding',
                  subtitle: 'Violet accents and a custom footer',
                  value: _branding,
                  onChanged: (value) => setState(() => _branding = value),
                  icon: Icons.workspace_premium_outlined,
                ),
              ],
            ),
          ),
          const SizedBox(height: AppSpacing.x3),
          AppTextField(
            controller: _footerController,
            label: 'Footer text',
            hint: 'Generated by MoneyMan',
          ),
          const SizedBox(height: AppSpacing.x5),
          Text('Preview', style: context.h3),
          const SizedBox(height: 8),
          AppCard(
            child: _loading
                ? const Padding(
                    padding: EdgeInsets.symmetric(vertical: AppSpacing.x6),
                    child: Center(child: CircularProgressIndicator()),
                  )
                : Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: <Widget>[
                      Text(_titleController.text, style: context.h3),
                      Text(
                        '${Fmt.date(_range.start.millisecondsSinceEpoch)} → ${Fmt.date(_range.end.millisecondsSinceEpoch)}',
                        style: context.caption,
                      ),
                      const SizedBox(height: AppSpacing.x3),
                      Row(
                        children: <Widget>[
                          Expanded(
                            child: _metric(context, 'Income', summary.income, palette.income),
                          ),
                          Expanded(
                            child: _metric(context, 'Expense', summary.expense, palette.expense),
                          ),
                          Expanded(
                            child: _metric(context, 'Net', summary.net, palette.accent),
                          ),
                        ],
                      ),
                      if (_includeCategories && _categories.isNotEmpty) ...<Widget>[
                        const SizedBox(height: AppSpacing.x3),
                        DonutChart(
                          totals: _categories,
                          total: _categories.fold<int>(0, (sum, item) => sum + item.total),
                          size: 130,
                        ),
                        const SizedBox(height: AppSpacing.x2),
                        RankedBars(totals: _categories, max: 5),
                      ],
                      if (_includeAccounts) ...<Widget>[
                        const SizedBox(height: AppSpacing.x2),
                        ...accounts.take(4).map(
                              (account) => Padding(
                                padding: const EdgeInsets.symmetric(vertical: 4),
                                child: Row(
                                  children: <Widget>[
                                    Expanded(
                                      child: Text(account.name,
                                          style: textStyleBody(context)),
                                    ),
                                    Text(
                                      Fmt.money(account.balance, forceCompact: true),
                                      style: AppTextStyles.money(12,
                                          color: palette.ink, weight: FontWeight.w600),
                                    ),
                                  ],
                                ),
                              ),
                            ),
                      ],
                    ],
                  ),
          ),
          const SizedBox(height: AppSpacing.x6),
          PrimaryButton(
            label: 'Export branded PDF',
            icon: Icons.picture_as_pdf_rounded,
            loading: _preparing,
            onPressed: _preparing ? null : _export,
          ),
        ],
      ),
    );
  }

  TextStyle textStyleBody(BuildContext context) => AppTextStyles.body(context.c.ink);

  Widget _metric(BuildContext context, String label, int value, Color tone) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        Text(label, style: context.caption),
        Text(
          Fmt.money(value, forceCompact: true),
          style: AppTextStyles.money(14, color: tone, weight: FontWeight.w700),
        ),
      ],
    );
  }
}
