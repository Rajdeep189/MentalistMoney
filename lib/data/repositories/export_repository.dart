class ExportRepository {
  ExportRepository(this._db, this._transactions, this._stats);

  final AppDatabase _db;
  final TransactionRepository _transactions;
  final StatsRepository _stats;

  Future<Directory> _outputDir() async {
    final dir = await getApplicationDocumentsDirectory();
    final exports = Directory(p.join(dir.path, 'exports'));
    if (!await exports.exists()) {
      await exports.create(recursive: true);
    }
    return exports;
  }

  // -------------------------------------------------------------------- CSV

  Future<File> exportCsv({
    required DateTime start,
    required DateTime end,
    TransactionFilter? filter,
  }) async {
    final db = await _db.database;
    final categories = <int, String>{
      for (final row in await db.query('categories'))
        (row['id'] as num).toInt(): row['name'] as String,
    };
    final accounts = <int, String>{
      for (final row in await db.query('accounts'))
        (row['id'] as num).toInt(): row['name'] as String,
    };

    final txns = await _transactions.query(
      filter ??
          TransactionFilter(
            startDate: start,
            endDate: end,
            sort: 'oldest',
          ),
      limit: 100000,
    );

    final rows = <List<dynamic>>[
      <dynamic>[
        'Date',
        'Time',
        'Type',
        'Amount',
        'Currency',
        'Category',
        'Account',
        'To Account',
        'Note',
        'Tags',
        'Payment Method',
        'Recurring',
        'Include in reports',
      ],
    ];

    for (final txn in txns) {
      final date = DateTime.fromMillisecondsSinceEpoch(txn.date);
      rows.add(<dynamic>[
        '${date.day.toString().padLeft(2, '0')}/${date.month.toString().padLeft(2, '0')}/${date.year}',
        '${date.hour.toString().padLeft(2, '0')}:${date.minute.toString().padLeft(2, '0')}',
        txn.type,
        (txn.amount / 100).toStringAsFixed(2),
        Fmt.currencyCode,
        categories[txn.categoryId] ?? '',
        accounts[txn.accountId] ?? '',
        accounts[txn.toAccountId] ?? '',
        txn.note ?? '',
        txn.tagNames.join('|'),
        txn.paymentMethod,
        txn.recurringRuleId == null ? '' : 'yes',
        txn.includeInReports ? 'yes' : 'no',
      ]);
    }

    final csv = const ListToCsvConverter().convert(rows);
    final dir = await _outputDir();
    final file = File(p.join(
      dir.path,
      'MoneyMan_${start.year}${start.month.toString().padLeft(2, '0')}${start.day.toString().padLeft(2, '0')}_to_${end.year}${end.month.toString().padLeft(2, '0')}${end.day.toString().padLeft(2, '0')}.csv',
    ));
    await file.writeAsString(csv);
    return file;
  }

