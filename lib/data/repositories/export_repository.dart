  Future<File> exportPdf({
    required DateTime start,
    required DateTime end,
    String title = 'MoneyMan report',
    bool includeTransactions = true,
    bool premiumBranding = false,
    String footer = 'Generated by MoneyMan',
    List<BudgetProgress> budgets = const <BudgetProgress>[],
  }) async {
    final summary = await _stats.summary(start, end);
    final categories = await _stats.categoryTotals(start, end);
    final incomes = await _stats.categoryTotals(start, end, type: kTypeIncome);
    final txns = await _transactions.query(
      TransactionFilter(startDate: start, endDate: end, sort: 'oldest'),
      limit: 2000,
    );

    final doc = pw.Document();
    final regular = pw.Font.ttf(await rootBundle.load('assets/fonts/Poppins-Regular.ttf'));
    final bold = pw.Font.ttf(await rootBundle.load('assets/fonts/Poppins-Bold.ttf'));
    final accent = PdfColor.fromInt(premiumBranding ? 0xFF7A55F0 : 0xFF916CFF);

    String money(int paise) => Fmt.money(paise);

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        theme: pw.ThemeData.withFont(base: regular, bold: bold),
        header: (context) => pw.Container(
          padding: const pw.EdgeInsets.only(bottom: 12),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: <pw.Widget>[
              pw.Text('MoneyMan', style: pw.TextStyle(font: bold, fontSize: 16, color: accent)),
              pw.Text(
                '${_date(start)} – ${_date(end)}',
                style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
              ),
            ],
          ),
        ),
        footer: (context) => pw.Container(
          padding: const pw.EdgeInsets.only(top: 8),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: <pw.Widget>[
              pw.Text(footer, style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
              pw.Text(
                'Page ${context.pageNumber} of ${context.pagesCount}',
                style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
              ),
            ],
          ),
        ),
        build: (context) => <pw.Widget>[
          pw.SizedBox(height: 8),
          pw.Text(title, style: pw.TextStyle(font: bold, fontSize: 22)),
          pw.SizedBox(height: 4),
          pw.Text('Track every Money. Own your money.',
              style: pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
          pw.SizedBox(height: 16),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: <pw.Widget>[
              _metric('Income', money(summary.income), PdfColors.green700),
              _metric('Expense', money(summary.expense), PdfColors.red700),
              _metric('Net savings', money(summary.net), accent),
              _metric('Savings rate', '${summary.savingsRate.toStringAsFixed(0)}%', PdfColors.blue700),
            ],
          ),
          pw.SizedBox(height: 20),
          pw.Text('Expense by category', style: pw.TextStyle(font: bold, fontSize: 14)),
          pw.SizedBox(height: 8),
          if (categories.isEmpty)
            pw.Text('No expenses in this period.', style: const pw.TextStyle(fontSize: 11))
          else
            pw.Table(
              border: pw.TableBorder.symmetric(
                inside: const pw.BorderSide(color: PdfColors.grey300, width: 0.5),
              ),
              children: <pw.TableRow>[
                pw.TableRow(
                  decoration: const pw.BoxDecoration(color: PdfColors.grey100),
                  children: <pw.Widget>[
                    _cell('Category', bold: true),
                    _cell('Transactions', bold: true),
                    _cell('Amount', bold: true, align: pw.TextAlign.right),
                    _cell('Share', bold: true, align: pw.TextAlign.right),
                  ],
                ),
                for (final category in categories.take(20))
                  pw.TableRow(children: <pw.Widget>[
                    _cell(category.name),
                    _cell('${category.count}'),
                    _cell(money(category.total), align: pw.TextAlign.right),
                    _cell(
                      '${((category.total / (summary.expense == 0 ? 1 : summary.expense)) * 100).toStringAsFixed(1)}%',
                      align: pw.TextAlign.right,
                    ),
                  ]),
              ],
            ),
          if (budgets.isNotEmpty) ...<pw.Widget>[
            pw.SizedBox(height: 20),
            pw.Text('Budget performance', style: pw.TextStyle(font: bold, fontSize: 14)),
            pw.SizedBox(height: 8),
            pw.Table(
              border: pw.TableBorder.symmetric(
                inside: const pw.BorderSide(color: PdfColors.grey300, width: 0.5),
              ),
              children: <pw.TableRow>[
                pw.TableRow(
                  decoration: const pw.BoxDecoration(color: PdfColors.grey100),
                  children: <pw.Widget>[
                    _cell('Budget', bold: true),
                    _cell('Spent', bold: true, align: pw.TextAlign.right),
                    _cell('Limit', bold: true, align: pw.TextAlign.right),
                    _cell('Used', bold: true, align: pw.TextAlign.right),
                  ],
                ),
                for (final budget in budgets)
                  pw.TableRow(children: <pw.Widget>[
                    _cell(budget.budget.name),
                    _cell(money(budget.spent), align: pw.TextAlign.right),
                    _cell(money(budget.amount), align: pw.TextAlign.right),
                    _cell(
                      '${(budget.ratio * 100).toStringAsFixed(0)}%',
                      align: pw.TextAlign.right,
                      color: budget.isOver ? PdfColors.red700 : PdfColors.green700,
                    ),
                  ]),
              ],
            ),
          ],
          if (incomes.isNotEmpty) ...<pw.Widget>[
            pw.SizedBox(height: 20),
            pw.Text('Income by category', style: pw.TextStyle(font: bold, fontSize: 14)),
            pw.SizedBox(height: 8),
            pw.Table(
              children: <pw.TableRow>[
                for (final category in incomes)
                  pw.TableRow(children: <pw.Widget>[
                    _cell(category.name),
                    _cell(money(category.total), align: pw.TextAlign.right),
                  ]),
              ],
            ),
          ],
          if (includeTransactions) ...<pw.Widget>[
            pw.SizedBox(height: 20),
            pw.Text('Transactions', style: pw.TextStyle(font: bold, fontSize: 14)),
            pw.SizedBox(height: 8),
            pw.Table(
              border: pw.TableBorder.symmetric(
                inside: const pw.BorderSide(color: PdfColors.grey300, width: 0.5),
              ),
              children: <pw.TableRow>[
                pw.TableRow(
                  decoration: const pw.BoxDecoration(color: PdfColors.grey100),
                  children: <pw.Widget>[
                    _cell('Date', bold: true),
                    _cell('Note', bold: true),
                    _cell('Type', bold: true),
                    _cell('Amount', bold: true, align: pw.TextAlign.right),
                  ],
                ),
                for (final txn in txns.take(250))
                  pw.TableRow(children: <pw.Widget>[
                    _cell(_date(DateTime.fromMillisecondsSinceEpoch(txn.date))),
                    _cell(txn.note ?? txn.paymentMethod),
                    _cell(txn.type),
                    _cell(
                      money(txn.amount),
                      align: pw.TextAlign.right,
                      color: txn.type == kTypeIncome
                          ? PdfColors.green700
                          : txn.type == kTypeTransfer
                              ? PdfColors.blue700
                              : PdfColors.red700,
                    ),
                  ]),
              ],
            ),
          ],
        ],
      ),
    );

    final dir = await _outputDir();
    final file = File(p.join(
      dir.path,
      'MoneyMan_report_${DateTime.now().millisecondsSinceEpoch}.pdf',
    ));
    await file.writeAsBytes(await doc.save());
    return file;
  }

  pw.Widget _metric(String label, String value, PdfColor color) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: <pw.Widget>[
        pw.Text(label, style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
        pw.SizedBox(height: 4),
        pw.Text(value, style: pw.TextStyle(fontSize: 14, color: color, fontWeight: pw.FontWeight.bold)),
      ],
    );
  }

  pw.Widget _cell(
    String text, {
    bool bold = false,
    pw.TextAlign align = pw.TextAlign.left,
    PdfColor? color,
  }) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 4, horizontal: 4),
      child: pw.Text(
        text,
        textAlign: align,
        style: pw.TextStyle(
          fontSize: 9,
          fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
          color: color ?? PdfColors.black,
        ),
      ),
    );
  }

  String _date(DateTime date) =>
      '${date.day.toString().padLeft(2, '0')}/${date.month.toString().padLeft(2, '0')}/${date.year}';

  // ------------------------------------------------------------------- JSON

  Future<File> exportBackupJson() async {
    final db = await _db.database;
    const tables = <String>[
      'settings',
      'accounts',
      'categories',
      'transactions',
      'tags',
      'transaction_tags',
      'attachments',
      'budgets',
      'budget_categories',
      'goals',
      'goal_contributions',
      'bills',
      'recurring_rules',
      'split_groups',
      'split_members',
      'split_expenses',
      'split_shares',
      'settlements',
      'achievements',
      'user_profile',
    ];
    final payload = <String, dynamic>{
      'app': 'MoneyMan',
      'schema_version': AppDatabase.schemaVersion,
      'created_at': DateTime.now().toIso8601String(),
      'tables': <String, dynamic>{
        for (final table in tables) table: await db.query(table),
      },
    };
    final dir = await _outputDir();
    final file = File(p.join(
      dir.path,
      'moneyman_backup_${DateTime.now().millisecondsSinceEpoch}.json',
    ));
    await file.writeAsString(const JsonEncoder.withIndent('  ').convert(payload));
    return file;
  }

  Future<String> restoreBackupJson(File file, {bool merge = false}) async {
    final raw = await file.readAsString();
    final decoded = jsonDecode(raw);
    if (decoded is! Map<String, dynamic>) {
      throw const FormatException('Invalid backup file');
    }
    final tables = decoded['tables'];
    if (tables is! Map<String, dynamic>) {
      throw const FormatException('Backup is missing table data');
    }
    final db = await _db.database;
    await db.transaction((txn) async {
      if (!merge) {
        for (final table in tables.keys) {
          if (table == 'settings') continue;
          await txn.delete(table);
        }
      }
      for (final entry in tables.entries) {
        final table = entry.key;
        final rows = entry.value;
        if (rows is! List) continue;
        for (final row in rows) {
          if (row is! Map) continue;
          final map = row.map((key, value) => MapEntry(key.toString(), value));
          await txn.insert(table, map, conflictAlgorithm: ConflictAlgorithm.replace);
        }
      }
    });
    _db.notifyChanged();
    return 'Restored ${tables.length} tables';
  }
